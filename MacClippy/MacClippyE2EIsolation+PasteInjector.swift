#if MACCLIPPY_E2E
import AppKit
import Foundation
import Darwin

import MacClippyCore
import MacClippyPlatform

extension MacClippyE2EIsolation {
    func makeObserver() -> PasteboardObserver {
        PasteboardObserver(
            reader: MacClippySystemPasteboardReader(
                pasteboard: pasteboard,
                sourceAppBundleID: { Self.sourceAppBundleIdentifier },
                accessCoordinator: pasteboardAccessCoordinator,
                onReadFailure: { [weak self] error in
                    self?.recordDiagnostic(category: "production-observer-pasteboard-read", error: error)
                }
            ),
            exclusionRules: MacClippyCore.CaptureExclusionRules(
                concealedPasteboardTypes: [],
                transientPasteboardTypes: [],
                autoGeneratedPasteboardTypes: [],
                excludedAppBundleIDs: [],
                excludedTextPatterns: [],
                captureAll: true
            ),
            writeSentinel: pasteboardWriteSentinel
        )
    }

    func makePasteInjector(
        recipient: MacClippyE2ERecipient,
        barrier: MacClippyE2EPasteBarrier
    ) -> MacClippyPasteInjector {
        MacClippyPasteInjector(
            pasteboard: pasteboard,
            isProcessTrusted: { barrier.waitForTrustCheck() },
            postEvents: { [weak recipient, weak self] _, _ in
                self?.dispatchPaste(recipient, route: .globalFallback)
            },
            postEventsToProcess: { [weak recipient, weak self] _, _, processIdentifier in
                guard processIdentifier == getpid() else { return }
                self?.dispatchPaste(recipient, route: .processTargeted)
            },
            writeSentinel: pasteboardWriteSentinel,
            pasteboardAccessCoordinator: pasteboardAccessCoordinator
        )
    }

    private func dispatchPaste(
        _ recipient: MacClippyE2ERecipient?,
        route: MacClippyE2ERecipient.PosterRoute
    ) {
        let insert = {
            MainActor.assumeIsolated {
                recipient?.insertFromPasteboard(
                    self.pasteboard,
                    accessCoordinator: self.pasteboardAccessCoordinator,
                    route: route
                )
            }
        }
        if Thread.isMainThread {
            insert()
        } else {
            DispatchQueue.main.sync(execute: insert)
        }
    }
}

#endif
